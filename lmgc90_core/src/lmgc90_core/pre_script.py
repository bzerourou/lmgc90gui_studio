"""Emit an auditable `pre.py`. This is the reproducibility artefact."""
from __future__ import annotations

import math
from typing import Any

from .entities import Avatar, ContactLaw, GranuloConfig, Material, Model, VisibilityRule
from .population import ParticlePopulation
from .project import Project
from .types import (
    AvatarType, RIGID_AVATARS_2D, RIGID_AVATARS_3D, STUDIO_ONLY_KEYS,
    material_type_name,
)


def emit_pre(project: Project, *, use_loop: bool = False) -> str:
    w: list[str] = []
    def L(s: str = "") -> None:
        w.append(s)

    L('"""')
    L(f"pre.py generated by lmgc90_core — project {project.name!r}")
    L(f"dimension = {project.dimension}    units = {project.units.value}")
    L(f"bodies    = {project.n_bodies}  (AoS {len(project.avatars)} + SoA {sum(len(p) for p in project.populations)})")
    L('"""')
    L("from pylmgc90 import pre")
    L("import importlib.resources")
    L("import numpy as np")
    L()
    from .numpy_compat import PRE_PY_CROSS_PATCH
    for line in PRE_PY_CROSS_PATCH.strip("\n").splitlines():
        L(line)
    L()
    if any(_is_gmsh_primitive(item) for item in project.avatars):
        for line in _gmsh_primitive_helper().splitlines():
            L(line)
        L()
    L("mats   = pre.materials()")
    L("mods   = pre.models()")
    L("bodies = pre.avatars()")
    L("tacts  = pre.tact_behavs()")
    L("sees   = pre.see_tables()")
    L("posts  = pre.postpro_commands()")
    L()

    L("# --- materials ---")
    for m in project.materials:
        L(_emit_material(m))
        L(f"mats.addMaterial(mat_{m.name})")
    L()
    L("# --- models ---")
    for m in project.models:
        L(_emit_model(m))
        L(f"mods.addModel(mod_{m.name})")
    L()

    L("# --- avatars ---")
    avatar_refs: dict[str, str] = {}
    i = 0
    batch_number = 0
    while i < len(project.avatars):
        av = project.avatars[i]
        if _is_rigids_from_mesh2d(av):
            L(_emit_rigids_from_mesh2d(av))
            bodies_ref = _mesh_rigids_ref(av)
            L(f"for _body in {bodies_ref}:")
            L("    bodies.addAvatar(_body)")
            avatar_refs[av.avatar_id] = f"{bodies_ref}[0]"
            L()
            i += 1
            continue
        signature = _loop_avatar_signature(av) if use_loop else None
        run_end = i + 1
        if signature is not None:
            while run_end < len(project.avatars):
                next_signature = _loop_avatar_signature(project.avatars[run_end])
                if next_signature != signature:
                    break
                run_end += 1

        if signature is not None and run_end - i > 1:
            batch = project.avatars[i:run_end]
            batch_name = f"_avatar_batch_{batch_number}"
            batch_lines = [
                f"# {len(batch)} equivalent avatars",
                f"{batch_name} = []",
            ]
            uses_radius = "_radius" in signature
            if uses_radius:
                batch_lines.append("for _center, _radius in (")
                for item in batch:
                    batch_lines.append(f"    ({item.center!r}, {item.radius!r}),")
            else:
                batch_lines.append("for _center in (")
                for item in batch:
                    batch_lines.append(f"    {item.center!r},")
            batch_lines.append("):")
            batch_lines.append("    " + _emit_avatar(
                av,
                center_expr="_center",
                radius_expr="_radius" if uses_radius else None,
                variable="_body",
            ))
            batch_lines.append(f"    {batch_name}.append(_body)")
            batch_lines.append("    bodies.addAvatar(_body)")

            expanded_lines = []
            for item in batch:
                ref = f"av_{_ident(item.avatar_id)}"
                expanded_lines.extend((
                    _emit_avatar(item),
                    f"bodies.addAvatar({ref})",
                ))
            if len("\n".join(batch_lines)) < len("\n".join(expanded_lines)):
                batch_number += 1
                for line in batch_lines:
                    L(line)
                for index, item in enumerate(batch):
                    avatar_refs[item.avatar_id] = f"{batch_name}[{index}]"
            else:
                for item in batch:
                    L(_emit_avatar(item))
                    ref = f"av_{_ident(item.avatar_id)}"
                    avatar_refs[item.avatar_id] = ref
                    L(f"bodies.addAvatar({ref})")
            L()
            i = run_end
            continue

        L(_emit_avatar(av))
        ref = f"av_{_ident(av.avatar_id)}"
        avatar_refs[av.avatar_id] = ref
        for line in _emit_contactors(av):
            L(line)
        L(f"bodies.addAvatar({ref})")
        L()
        i += 1

    if project.populations:
        L("# --- particle populations (SoA → pre.rigidDisk/Sphere loop) ---")
        for pop in project.populations:
            L(_emit_population(pop))
            L()

    if project.laws:
        L("# --- contact laws ---")
        for law in project.laws:
            L(_emit_law(law))
            L(f"tacts.addBehav(law_{law.name})")
        L()

    if project.visibility:
        L("# --- see tables ---")
        for i, rule in enumerate(project.visibility):
            L(_emit_see(rule, i))
            L(f"sees.addSeeTable(see_{i})")
        L()

    if project.operations:
        L("# --- boundary conditions ---")
        for op in project.operations:
            L(_emit_dof(project, op, avatar_refs))
        L()

    if project.postpro:
        L("# --- post-processing ---")
        for cmd in project.postpro:
            L(_emit_postpro(project, cmd, avatar_refs))
        L()

    L("pre.writeDatbox(")
    L(f"    dim={project.dimension}, mats=mats, mods=mods, tacts=tacts,")
    L("    sees=sees, bodies=bodies, post=posts,")
    L(")")
    return "\n".join(w) + "\n"


def emit_equivalent(project: Project, obj) -> str:
    if isinstance(obj, Material):
        return _emit_material(obj)
    if isinstance(obj, Model):
        return _emit_model(obj)
    if isinstance(obj, Avatar):
        return _emit_avatar(obj)
    if isinstance(obj, ParticlePopulation):
        return _emit_population(obj)
    if isinstance(obj, ContactLaw):
        return _emit_law(obj)
    if isinstance(obj, VisibilityRule):
        return _emit_see(obj, 0)
    if isinstance(obj, GranuloConfig):
        return (
            f"# granulo {obj.container_type} n={obj.nb_particles} "
            f"r=[{obj.radius_min}, {obj.radius_max}] → ParticlePopulation"
        )
    return f"# no pre.* equivalent for {type(obj).__name__}"


def _ident(avatar_id: str) -> str:
    return avatar_id.replace("-", "_")


def _canonical_gmsh_primitive(geom: Any) -> str | None:
    key = str(geom or "").strip().lower()
    return {
        "disque": "Disque",
        "disk2d": "Disque",
        "sphère": "Sphère",
        "sphere": "Sphère",
        "sphere3d": "Sphère",
        "cylindre": "Cylindre",
        "cylinder3d": "Cylindre",
    }.get(key)


def _is_gmsh_primitive(avatar: Avatar) -> bool:
    return (
        avatar.avatar_type == AvatarType.MESH_DEFORMABLE
        and _canonical_gmsh_primitive(
            (avatar.mesh_params or {}).get("geom")
        ) is not None
    )


def _gmsh_primitive_helper() -> str:
    return '''def _lmgc90_gmsh_primitive(geom, center, params):
    import gmsh
    import os
    import tempfile
    radius = float(params["r"])
    if radius <= 0:
        raise ValueError(f"{geom} mesh requires a positive radius")
    if geom == "Disque":
        dimension = 2
        mesh_size = min(
            radius / max(1, int(params.get("nr", 8))),
            2.0 * math.pi * radius / max(3, int(params.get("ntheta", 24))),
        )
    elif geom == "Cylindre":
        height = float(params["h"])
        if height <= 0:
            raise ValueError("Cylindre mesh requires a positive height")
        dimension = 3
        mesh_size = min(
            radius / max(1, int(params.get("nr", 8))),
            2.0 * math.pi * radius / max(3, int(params.get("ntheta", 24))),
            height / max(1, int(params.get("nz", 4))),
        )
    else:
        dimension = 3
        mesh_size = min(
            radius / max(1, int(params.get("nr", 8))),
            2.0 * math.pi * radius / max(3, int(params.get("ntheta", 24))),
            math.pi * radius / max(3, int(params.get("nphi", 12))),
        )
    with tempfile.TemporaryDirectory(prefix="lmgc90_primitive_mesh_") as folder:
        mesh_path = os.path.join(folder, "primitive.msh")
        gmsh.initialize()
        try:
            gmsh.model.add("lmgc90_primitive")
            gmsh.option.setNumber("General.Terminal", 0)
            gmsh.option.setNumber("Mesh.CharacteristicLengthMax", mesh_size)
            gmsh.option.setNumber("Mesh.CharacteristicLengthMin", mesh_size * 0.2)
            if geom == "Disque":
                gmsh.model.occ.addDisk(center[0], center[1], 0.0, radius, radius)
            elif geom == "Cylindre":
                gmsh.model.occ.addCylinder(
                    center[0], center[1], center[2] - height / 2.0,
                    0.0, 0.0, height, radius,
                )
            else:
                z = center[2] if len(center) > 2 else 0.0
                gmsh.model.occ.addSphere(center[0], center[1], z, radius)
            gmsh.model.occ.synchronize()
            gmsh.model.mesh.generate(dimension)
            gmsh.write(mesh_path)
        finally:
            gmsh.finalize()
        return pre.readMesh(mesh_path, dimension)
'''


def _is_rigids_from_mesh2d(av: Avatar) -> bool:
    mesh_params = av.mesh_params or {}
    geom = str(mesh_params.get("geom") or "").lower()
    return (
        geom in ("rigidsfrommesh2d", "rigids_from_mesh2d")
        or mesh_params.get("source") == "rigidsFromMesh2D"
    )


def _mesh_rigids_ref(av: Avatar) -> str:
    return f"_mesh_rigids_{_ident(av.avatar_id)}"


def _population_bodies_ref(population: ParticlePopulation) -> str:
    ident = population.population_id[:12].replace("-", "_")
    return f"_population_bodies_{ident}"


def _kw(d: dict[str, Any]) -> str:
    parts = []
    for k, v in d.items():
        parts.append(f"{k}={v!r}")
    return ", ".join(parts)


def _emit_material(m: Material) -> str:
    extra = (", " + _kw(m.properties)) if m.properties else ""
    return (
        f"mat_{m.name} = pre.material(name={m.name!r}, "
        f"materialType={material_type_name(m.material_type)!r}, "
        f"density={m.density}{extra})"
    )


def _emit_model(m: Model) -> str:
    extra = (", " + _kw(m.options)) if m.options else ""
    return (
        f"mod_{m.name} = pre.model(name={m.name!r}, physics={m.physics!r}, "
        f"element={m.element!r}, dimension={m.dimension}{extra})"
    )


def _loop_avatar_signature(av: Avatar) -> str | None:
    if av.contactors or av.avatar_type in (
        AvatarType.MESH_DEFORMABLE, AvatarType.EMPTY_AVATAR,
    ):
        return None
    return _emit_avatar(
        av,
        center_expr="_center",
        radius_expr="_radius",
        variable="_body",
    )


def _emit_avatar(
    av: Avatar,
    *,
    center_expr: str | None = None,
    radius_expr: str | None = None,
    variable: str | None = None,
) -> str:
    ident = _ident(av.avatar_id)
    target = variable or f"av_{ident}"
    mat, mod = f"mat_{av.material_name}", f"mod_{av.model_name}"
    c = center_expr if center_expr is not None else av.center
    radius = radius_expr if radius_expr is not None else av.radius
    color = av.color
    t = av.avatar_type
    if t == AvatarType.RIGID_DISK:
        hollow = ", is_Hollow=True" if av.is_hollow else ""
        return (
            f"{target} = pre.rigidDisk(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r}{hollow})"
        )
    if t == AvatarType.RIGID_SPHERE:
        return (
            f"{target} = pre.rigidSphere(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r})"
        )
    if t == AvatarType.RIGID_DISCRETE:
        return (
            f"{target} = pre.rigidDiscreteDisk(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r})"
        )
    if t == AvatarType.RIGID_JONC:
        ax = av.axis or {}
        return (
            f"{target} = pre.rigidJonc(axe1={ax.get('axe1')}, axe2={ax.get('axe2')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r})"
        )
    if t == AvatarType.SMOOTH_WALL:
        wp = av.wall_params or {}
        return (
            f"{target} = pre.smoothWall(l={wp.get('l')}, h={wp.get('h')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_polyg={wp.get('nb_polyg', 10)})"
        )
    if t == AvatarType.ROUGH_WALL:
        wp = av.wall_params or {}
        return (
            f"{target} = pre.roughWall(l={wp.get('l')}, r={wp.get('r')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_vertex={wp.get('nb_vertex', 10)})"
        )
    if t == AvatarType.ROUGH_WALL_3D:
        wp = av.wall_params or {}
        return (
            f"{target} = pre.roughWall3D(lx={wp.get('lx', 1.0)}, ly={wp.get('ly', 1.0)}, "
            f"lz={wp.get('lz', 0.1)}, center={c}, model={mod}, material={mat}, color={color!r})"
        )
    if t == AvatarType.FINE_WALL:
        wp = av.wall_params or {}
        radius = wp.get("h", 2.0 * wp.get("r", 0.02)) / 2.0
        return (
            f"{target} = pre.fineWall(l={wp.get('l')}, r={radius}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_vertex={wp.get('nb_vertex', 10)})"
        )
    if t == AvatarType.GRANULO_WALL:
        wp = av.wall_params or {}
        max_radius = wp.get("h", 2.0 * wp.get("rmax", 0.03)) / 2.0
        return (
            f"{target} = pre.granuloRoughWall(l={wp.get('l')}, "
            f"rmin={wp.get('rmin')}, rmax={max_radius}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_vertex={wp.get('nb_vertex', 10)})"
        )
    if t == AvatarType.GRANULO_ROUGH_WALL_3D:
        wp = av.wall_params or {}
        return (
            f"{target} = pre.granuloRoughWall3D(lx={wp.get('lx', 1.0)}, ly={wp.get('ly', 1.0)}, "
            f"lz={wp.get('lz', 0.1)}, rmin={wp.get('rmin', 0.01)}, rmax={wp.get('rmax', 0.02)}, "
            f"center={c}, model={mod}, material={mat}, color={color!r})"
        )
    if t == AvatarType.RIGID_CLUSTER:
        return (
            f"{target} = pre.rigidCluster(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r}, nb_disk={av.nb_vertices})"
        )
    if t == AvatarType.RIGID_CYLINDER:
        wp = av.wall_params or {}
        hollow = ", is_Hollow=True" if av.is_hollow else ""
        return (
            f"{target} = pre.rigidCylinder(r={radius}, h={wp.get('h')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}{hollow})"
        )
    if t == AvatarType.RIGID_PLAN:
        ax = av.axis or {}
        return (
            f"{target} = pre.rigidPlan(center={c}, model={mod}, material={mat}, "
            f"color={color!r}, axe1={ax.get('axe1')}, axe2={ax.get('axe2')}, axe3={ax.get('axe3')})"
        )
    if t == AvatarType.RIGID_OVOID:
        kwargs = [f"center={c}", f"model={mod}", f"material={mat}", f"color={color!r}"]
        if radius is not None:
            kwargs.append(f"radius={radius}")
        if av.vertices is not None:
            kwargs.append(f"vertices=np.array({av.vertices!r})")
        return f"{target} = pre.rigidOvoidPolygon({', '.join(kwargs)})"
    if t == AvatarType.RIGID_POLYGON:
        if av.generation_type == "regular":
            return (
                f"{target} = pre.rigidPolygon(model={mod}, material={mat}, center={c}, "
                f"color={color!r}, generation_type='regular', nb_vertices={av.nb_vertices}, "
                f"radius={radius})"
            )
        vertices = [
            [float(point[index]) - float(av.center[index]) for index in range(2)]
            for point in av.vertices or []
        ]
        return (
            f"{target} = pre.rigidPolygon(model={mod}, material={mat}, center={c}, "
            f"color={color!r}, generation_type='full', "
            f"vertices=np.array({vertices!r}))"
        )
    if t == AvatarType.RIGID_POLYHEDRON:
        if av.generation_type == "regular":
            return (
                f"{target} = pre.rigidPolyhedron(model={mod}, material={mat}, "
                f"center={c}, color={color!r}, generation_type='regular', "
                f"nb_vertices={av.nb_vertices}, radius={radius})"
            )
        return (
            f"{target} = pre.rigidPolyhedron(model={mod}, material={mat}, "
            f"center={c}, color={color!r}, generation_type='vertices', "
            f"vertices=np.array({av.vertices}))"
        )
    if t == AvatarType.MESH_DEFORMABLE:
        mp = av.mesh_params or {}
        geom = mp.get("geom")
        if (
            str(geom or "").lower()
            in ("deformablebrick", "deformable_brick", "brick")
            or mp.get("source") == "deformableBrick"
            or "brick_lx" in mp
        ):
            brick_lx = float(mp.get("brick_lx") or mp.get("lx") or 0.1)
            brick_ly = float(mp.get("brick_ly") or mp.get("ly") or 0.05)
            brick_name = str(mp.get("brick_name", "brique"))
            apabh = mp.get("apabh") or mp.get("apab_brick") or [0.25, 0.75]
            apabv = mp.get("apabv") or mp.get("apab_brick") or [0.25, 0.75]
            kwargs = [
                f"center={c}",
                f"material={mat}",
                f"model={mod}",
                f"mesh_type={mp.get('mesh_type', 'Q4')!r}",
                f"nb_elem_x={int(mp.get('nb_elem_x', mp.get('nx', 2)))!r}",
                f"nb_elem_y={int(mp.get('nb_elem_y', mp.get('ny', 2)))!r}",
                f"apabh={apabh!r}",
                f"apabv={apabv!r}",
            ]
            if mp.get("colors") is not None:
                kwargs.append(f"colors={mp['colors']!r}")
            return (
                f"_brick_{ident} = pre.brick2D({brick_name!r}, "
                f"{brick_lx!r}, {brick_ly!r})\n"
                f"{target} = _brick_{ident}.deformableBrick("
                f"{', '.join(kwargs)})"
            )
        if geom == "Rectangle":
            x0 = mp["cx"] - mp["lx"] / 2.0
            y0 = mp["cy"] - mp["ly"] / 2.0
            return (
                f"mesh_{ident} = pre.buildMesh2D({mp.get('mesh_type', '2T3')!r}, "
                f"{x0}, {y0}, {mp['lx']}, {mp['ly']}, {mp['nx']}, {mp['ny']})\n"
                f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        if geom == "Boîte (H8)":
            x0 = mp["cx"] - mp["lx"] / 2.0
            y0 = mp["cy"] - mp["ly"] / 2.0
            z0 = mp.get("cz", 0.0) - mp["lz"] / 2.0
            return (
                f"mesh_{ident} = pre.buildMeshH8({x0}, {y0}, {z0}, "
                f"{mp['lx']}, {mp['ly']}, {mp['lz']}, {mp['nx']}, {mp['ny']}, {mp['nz']})\n"
                f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        primitive_geom = _canonical_gmsh_primitive(geom)
        if primitive_geom is not None:
            return (
                f"mesh_{ident} = _lmgc90_gmsh_primitive("
                f"{primitive_geom!r}, {c}, {mp!r})\n"
                f"{target} = pre.buildMeshedAvatar("
                f"mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        if geom == "Fichier externe":
            filepath = str(mp.get("filepath", ""))
            if filepath.startswith("pkg://"):
                package, separator, resource_name = filepath[6:].partition("/")
                parts = resource_name.split("/")
                if not separator or not package or any(
                    part in ("", ".", "..") for part in parts
                ):
                    raise ValueError(f"invalid package mesh reference: {filepath!r}")
                resource_parts = ", ".join(repr(part) for part in parts)
                mesh_file = f"_mesh_file_{ident}"
                return "\n".join((
                    f"with importlib.resources.as_file(importlib.resources.files({package!r}).joinpath({resource_parts})) as {mesh_file}:",
                    f"    mesh_{ident} = pre.readMesh(str({mesh_file}), {mp.get('dim', 2)})",
                    f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})",
                ))
            return (
                f"mesh_{ident} = pre.readMesh({filepath!r}, {mp.get('dim', 2)})\n"
                f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        raise NotImplementedError(
            f"pre.py emission is not implemented for mesh geometry {geom!r} "
            f"(avatar_id={av.avatar_id})"
        )
    if t == AvatarType.EMPTY_AVATAR:
        wp = av.wall_params or {}
        if wp.get("brick_name") and any(
            wp.get(key) is not None for key in ("l", "lx", "h", "ly")
        ):
            lx = wp.get("l") if wp.get("l") is not None else wp.get("lx")
            ly = wp.get("h") if wp.get("h") is not None else wp.get("ly")
            if lx is None or ly is None:
                raise ValueError(
                    f"brick wall_params need l/h or lx/ly "
                    f"(avatar_id={av.avatar_id})"
                )
            brick = f"_brick_{ident}"
            return (
                f"{brick} = pre.brick2D({str(wp['brick_name'])!r}, "
                f"{float(lx)!r}, {float(ly)!r})\n"
                f"{target} = {brick}.rigidBrick("
                f"center={c}, model={mod}, material={mat}, color={color!r})"
            )
        dimension = 3 if len(av.center) >= 3 else 2
        return "\n".join((
            f"{target} = pre.avatar({dimension})",
            f"{target}.addBulk(pre.rigid{dimension}d())",
            f"{target}.addNode(pre.node(coor=np.asarray({c}, dtype=float), number=1))",
            f"{target}.defineGroups()",
            f"{target}.defineModel(model={mod})",
            f"{target}.defineMaterial(material={mat})",
        ))
    raise NotImplementedError(
        f"pre.py emission is not implemented for avatar type {t.value!r} "
        f"(avatar_id={av.avatar_id})"
    )


def _emit_rigids_from_mesh2d(av: Avatar) -> str:
    mesh_params = av.mesh_params or {}
    filepath = str(mesh_params.get("filepath") or mesh_params.get("file") or "")
    if not filepath:
        raise ValueError(
            f"rigidsFromMesh2D requires a mesh filepath (avatar_id={av.avatar_id})"
        )
    dim = int(mesh_params.get("dim", 2))
    ident = _ident(av.avatar_id)
    mesh_ref = f"_mesh_{ident}"
    bodies_ref = _mesh_rigids_ref(av)
    mod = f"mod_{av.model_name}"
    mat = f"mat_{av.material_name}"

    if filepath.startswith("pkg://"):
        package, separator, resource_name = filepath[6:].partition("/")
        parts = resource_name.split("/")
        if not separator or not package or any(
            part in ("", ".", "..") for part in parts
        ):
            raise ValueError(f"invalid package mesh reference: {filepath!r}")
        resource_parts = ", ".join(repr(part) for part in parts)
        mesh_file = f"_mesh_file_{ident}"
        read_mesh = (
            f"with importlib.resources.as_file("
            f"importlib.resources.files({package!r}).joinpath({resource_parts})"
            f") as {mesh_file}:\n"
            f"    {mesh_ref} = pre.readMesh(str({mesh_file}), {dim})"
        )
    else:
        read_mesh = f"{mesh_ref} = pre.readMesh({filepath!r}, {dim})"

    return "\n".join((
        f"# rigid polygons from surface mesh {filepath!r}",
        read_mesh,
        f"{bodies_ref} = list(pre.rigidsFromMesh2D("
        f"surfacic_mesh={mesh_ref}, model={mod}, material={mat}, "
        f"color={av.color or 'BLEUx'!r}))",
    ))


def _emit_contactors(av: Avatar) -> list[str]:
    ident = _ident(av.avatar_id)
    lines: list[str] = []
    for index, contactor in enumerate(av.contactors):
        shape = contactor.get("shape")
        if not shape:
            continue
        options = dict(contactor.get("params") or {})
        options.update({
            key: value for key, value in contactor.items()
            if key not in ("shape", "color", "params")
        })
        shape_key = str(shape).upper()
        generation_type = options.pop("generation_type", None)
        shift = options.pop("shift", None)

        if shape_key == "POLYG":
            if generation_type == "regular":
                count = int(options.pop("nb_vertices"))
                radius = float(options.pop("radius"))
                options["vertices"] = [
                    [
                        radius * math.cos(2.0 * math.pi * vertex / count),
                        radius * math.sin(2.0 * math.pi * vertex / count),
                    ]
                    for vertex in range(count)
                ]
                options["nb_vertices"] = count
            elif generation_type == "full":
                options["nb_vertices"] = len(options["vertices"])
            if shift is not None:
                options["vertices"] = [
                    [coordinate + shift[axis] for axis, coordinate in enumerate(vertex)]
                    for vertex in options["vertices"]
                ]

        elif shape_key == "POLYR":
            if generation_type == "regular":
                count = int(options.pop("nb_vertices"))
                radius = float(options.pop("radius"))
                vertices_name = f"_contactor_{ident}_{index}_vertices"
                faces_name = f"_contactor_{ident}_{index}_faces"
                lines.extend((
                    f"{faces_name}, {vertices_name} = pre.buildPolyhedronConnectivity("
                    f"pre.getRegularPolyhedronVertices({count}, {radius!r}))",
                ))
                options["vertices"] = vertices_name
                options["connectivity"] = faces_name
                options["nb_vertices"] = f"len({vertices_name})"
                options["nb_faces"] = f"len({faces_name})"
            elif generation_type == "full":
                options["nb_vertices"] = len(options["vertices"])
                options["nb_faces"] = len(options["connectivity"])
            if shift is not None:
                if isinstance(options["vertices"], str):
                    vertices_name = options["vertices"]
                    shifted_name = f"_contactor_{ident}_{index}_shifted_vertices"
                    lines.append(
                        f"{shifted_name} = {vertices_name} + np.array({shift!r})"
                    )
                    options["vertices"] = shifted_name
                else:
                    options["vertices"] = [
                        [coordinate + shift[axis] for axis, coordinate in enumerate(vertex)]
                        for vertex in options["vertices"]
                    ]

        kwargs = []
        for key, value in options.items():
            if key in ("nb_vertices", "nb_faces") and isinstance(value, str):
                value = value
            else:
                value = repr(value)
            kwargs.append(f"{key}={value}")
        extra = ", " + ", ".join(kwargs) if kwargs else ""
        color = contactor.get("color", av.color)
        shift_arg = f", shift={shift!r}" if shift is not None else ""
        lines.append(
            f"av_{ident}.addContactors(shape={shape!r}, color={color!r}{extra}{shift_arg})"
        )
    rigid_types = RIGID_AVATARS_2D | RIGID_AVATARS_3D | {AvatarType.EMPTY_AVATAR}
    if lines and av.avatar_type in rigid_types:
        lines.append(f"av_{ident}.computeRigidProperties()")
    return lines


def _emit_population(pop: ParticlePopulation) -> str:
    fn_map = {
        AvatarType.RIGID_DISK: "rigidDisk",
        AvatarType.RIGID_SPHERE: "rigidSphere",
        AvatarType.RIGID_DISCRETE: "rigidDiscreteDisk",
        AvatarType.RIGID_CLUSTER: "rigidCluster",
        AvatarType.RIGID_CYLINDER: "rigidCylinder",
        AvatarType.RIGID_POLYGON: "rigidPolygon",
        AvatarType.RIGID_POLYHEDRON: "rigidPolyhedron",
    }
    fn = fn_map.get(pop.avatar_type)
    if fn is None:
        raise ValueError(
            f"pre.py population emission is not implemented for "
            f"avatar type {pop.avatar_type!r}"
        )
    extra = ""
    if pop.avatar_type == AvatarType.RIGID_CLUSTER:
        extra = f", nb_disk={pop.extra_params.get('nb_disk', 3)}"
    if pop.avatar_type == AvatarType.RIGID_CYLINDER:
        extra = f", h={pop.extra_params.get('h', 1.0)}"
    if pop.avatar_type in (AvatarType.RIGID_POLYGON, AvatarType.RIGID_POLYHEDRON):
        nb_default = 6 if pop.avatar_type == AvatarType.RIGID_POLYGON else 8
        radius_arg = (
            f"generation_type={pop.extra_params.get('generation_type', 'regular')!r}, "
            f"nb_vertices={int(pop.extra_params.get('nb_vertices', nb_default))}, "
            "radius=float(_r)"
        )
        extra = ""
    else:
        radius_arg = "r=float(_r)"
    ident = pop.population_id[:12].replace("-", "_")
    bodies_ref = _population_bodies_ref(pop)
    return "\n".join([
        f"# population {pop.population_id}  n={len(pop)}  {pop.avatar_type.value}",
        f"{bodies_ref} = []",
        f"centers_{ident} = np.array({pop.centers.tolist()})",
        f"radii_{ident}   = np.array({pop.radii.tolist()})",
        f"for _i, (_c, _r) in enumerate(zip(centers_{ident}, radii_{ident})):",
        f"    _body = pre.{fn}({radius_arg}, center=_c, model=mod_{pop.model_name}, "
        f"material=mat_{pop.material_name}, color={pop.color!r}{extra})",
        f"    bodies.addAvatar(_body)",
        f"    {bodies_ref}.append(_body)",
    ])


def _emit_law(law: ContactLaw) -> str:
    fric = f", fric={law.friction}" if law.friction is not None else ""
    extra = (", " + _kw(law.properties)) if law.properties else ""
    return (
        f"law_{law.name} = pre.tact_behav(name={law.name!r}, "
        f"law={law.law_type_name!r}{fric}{extra})"
    )


