"""Emit an auditable `pre.py`. This is the reproducibility artefact."""
from __future__ import annotations

import math
from typing import Any

from .entities import Avatar, ContactLaw, GranuloConfig, Material, Model, VisibilityRule
from .population import ParticlePopulation
from .project import Project
from .types import AvatarType


def emit_pre(project: Project, *, use_loop: bool = False) -> str:
    w: list[str] = []
    def L(s: str = "") -> None:
        w.append(s)

    L('"""')
    L(f"pre.py generated by lmgc90_core — project {project.name!r}")
    L(f"dimension = {project.dimension}    units = {project.units.value}")
    L(f"bodies    = {project.n_bodies}  (AoS {len(project.avatars)} + SoA {sum(len(p) for p in project.populations)})")
    L('"""')
    L("from pylmgc90 import pre")
    L("import numpy as np")
    L()
    from .numpy_compat import PRE_PY_CROSS_PATCH
    for line in PRE_PY_CROSS_PATCH.strip("\n").splitlines():
        L(line)
    L()
    L("mats   = pre.materials()")
    L("mods   = pre.models()")
    L("bodies = pre.avatars()")
    L("tacts  = pre.tact_behavs()")
    L("sees   = pre.see_tables()")
    L("posts  = pre.postpro_commands()")
    L()

    L("# --- materials ---")
    for m in project.materials:
        L(_emit_material(m))
        L(f"mats.addMaterial(mat_{m.name})")
    L()
    L("# --- models ---")
    for m in project.models:
        L(_emit_model(m))
        L(f"mods.addModel(mod_{m.name})")
    L()

    L("# --- avatars ---")
    avatar_refs: dict[str, str] = {}
    i = 0
    batch_number = 0
    while i < len(project.avatars):
        av = project.avatars[i]
        signature = _loop_avatar_signature(av) if use_loop else None
        run_end = i + 1
        if signature is not None:
            while run_end < len(project.avatars):
                next_signature = _loop_avatar_signature(project.avatars[run_end])
                if next_signature != signature:
                    break
                run_end += 1

        if signature is not None and run_end - i > 1:
            batch = project.avatars[i:run_end]
            batch_name = f"_avatar_batch_{batch_number}"
            batch_lines = [
                f"# {len(batch)} equivalent avatars",
                f"{batch_name} = []",
            ]
            uses_radius = "_radius" in signature
            if uses_radius:
                batch_lines.append("for _center, _radius in (")
                for item in batch:
                    batch_lines.append(f"    ({item.center!r}, {item.radius!r}),")
            else:
                batch_lines.append("for _center in (")
                for item in batch:
                    batch_lines.append(f"    {item.center!r},")
            batch_lines.append("):")
            batch_lines.append("    " + _emit_avatar(
                av,
                center_expr="_center",
                radius_expr="_radius" if uses_radius else None,
                variable="_body",
            ))
            batch_lines.append(f"    {batch_name}.append(_body)")
            batch_lines.append("    bodies.addAvatar(_body)")

            expanded_lines = []
            for item in batch:
                ref = f"av_{_ident(item.avatar_id)}"
                expanded_lines.extend((
                    _emit_avatar(item),
                    f"bodies.addAvatar({ref})",
                ))
            if len("\n".join(batch_lines)) < len("\n".join(expanded_lines)):
                batch_number += 1
                for line in batch_lines:
                    L(line)
                for index, item in enumerate(batch):
                    avatar_refs[item.avatar_id] = f"{batch_name}[{index}]"
            else:
                for item in batch:
                    L(_emit_avatar(item))
                    ref = f"av_{_ident(item.avatar_id)}"
                    avatar_refs[item.avatar_id] = ref
                    L(f"bodies.addAvatar({ref})")
            L()
            i = run_end
            continue

        L(_emit_avatar(av))
        ref = f"av_{_ident(av.avatar_id)}"
        avatar_refs[av.avatar_id] = ref
        for line in _emit_contactors(av):
            L(line)
        if av.avatar_type == AvatarType.EMPTY_AVATAR and av.contactors:
            L(f"{ref}.computeRigidProperties()")
        L(f"bodies.addAvatar({ref})")
        L()
        i += 1

    if project.populations:
        L("# --- particle populations (SoA → pre.rigidDisk/Sphere loop) ---")
        for pop in project.populations:
            L(_emit_population(pop))
            L()

    if project.laws:
        L("# --- contact laws ---")
        for law in project.laws:
            L(_emit_law(law))
            L(f"tacts.addBehav(law_{law.name})")
        L()

    if project.visibility:
        L("# --- see tables ---")
        for i, rule in enumerate(project.visibility):
            L(_emit_see(rule, i))
            L(f"sees.addSeeTable(see_{i})")
        L()

    if project.operations:
        L("# --- boundary conditions ---")
        for op in project.operations:
            L(_emit_dof(project, op, avatar_refs))
        L()

    if project.postpro:
        L("# --- post-processing ---")
        for cmd in project.postpro:
            tgt = ""
            if cmd.target_type != "global" and cmd.target_value is not None:
                tgt = f", {cmd.target_type}={cmd.target_value!r}"
            L(f"posts.addCommand(pre.postpro_command(name={cmd.name!r}, step={cmd.step}{tgt}))")
        L()

    L("pre.writeDatbox(")
    L(f"    dim={project.dimension}, mats=mats, mods=mods, tacts=tacts,")
    L("    sees=sees, bodies=bodies, post=posts,")
    L(")")
    return "\n".join(w) + "\n"


def emit_equivalent(project: Project, obj) -> str:
    if isinstance(obj, Material):
        return _emit_material(obj)
    if isinstance(obj, Model):
        return _emit_model(obj)
    if isinstance(obj, Avatar):
        return _emit_avatar(obj)
    if isinstance(obj, ParticlePopulation):
        return _emit_population(obj)
    if isinstance(obj, ContactLaw):
        return _emit_law(obj)
    if isinstance(obj, VisibilityRule):
        return _emit_see(obj, 0)
    if isinstance(obj, GranuloConfig):
        return (
            f"# granulo {obj.container_type} n={obj.nb_particles} "
            f"r=[{obj.radius_min}, {obj.radius_max}] → ParticlePopulation"
        )
    return f"# no pre.* equivalent for {type(obj).__name__}"


def _ident(avatar_id: str) -> str:
    return avatar_id[:8]


def _kw(d: dict[str, Any]) -> str:
    parts = []
    for k, v in d.items():
        parts.append(f"{k}={v!r}")
    return ", ".join(parts)


def _emit_material(m: Material) -> str:
    extra = (", " + _kw(m.properties)) if m.properties else ""
    return (
        f"mat_{m.name} = pre.material(name={m.name!r}, "
        f"materialType={m.material_type.value!r}, density={m.density}{extra})"
    )


def _emit_model(m: Model) -> str:
    extra = (", " + _kw(m.options)) if m.options else ""
    return (
        f"mod_{m.name} = pre.model(name={m.name!r}, physics={m.physics!r}, "
        f"element={m.element!r}, dimension={m.dimension}{extra})"
    )


def _loop_avatar_signature(av: Avatar) -> str | None:
    if av.contactors or av.avatar_type in (
        AvatarType.MESH_DEFORMABLE, AvatarType.EMPTY_AVATAR,
    ):
        return None
    return _emit_avatar(
        av,
        center_expr="_center",
        radius_expr="_radius",
        variable="_body",
    )


def _emit_avatar(
    av: Avatar,
    *,
    center_expr: str | None = None,
    radius_expr: str | None = None,
    variable: str | None = None,
) -> str:
    ident = _ident(av.avatar_id)
    target = variable or f"av_{ident}"
    mat, mod = f"mat_{av.material_name}", f"mod_{av.model_name}"
    c = center_expr if center_expr is not None else av.center
    radius = radius_expr if radius_expr is not None else av.radius
    color = av.color
    t = av.avatar_type
    if t == AvatarType.RIGID_DISK:
        hollow = ", is_Hollow=True" if av.is_hollow else ""
        return (
            f"{target} = pre.rigidDisk(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r}{hollow})"
        )
    if t == AvatarType.RIGID_SPHERE:
        hollow = ", is_Hollow=True" if av.is_hollow else ""
        return (
            f"{target} = pre.rigidSphere(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r}{hollow})"
        )
    if t == AvatarType.RIGID_JONC:
        ax = av.axis or {}
        return (
            f"{target} = pre.rigidJonc(axe1={ax.get('axe1')}, axe2={ax.get('axe2')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r})"
        )
    if t == AvatarType.SMOOTH_WALL:
        wp = av.wall_params or {}
        return (
            f"{target} = pre.smoothWall(l={wp.get('l')}, h={wp.get('h')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_polyg={wp.get('nb_polyg', 10)})"
        )
    if t == AvatarType.ROUGH_WALL:
        wp = av.wall_params or {}
        return (
            f"{target} = pre.roughWall(l={wp.get('l')}, r={wp.get('r')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_vertex={wp.get('nb_vertex', 10)})"
        )
    if t == AvatarType.FINE_WALL:
        wp = av.wall_params or {}
        radius = wp.get("h", 2.0 * wp.get("r", 0.02)) / 2.0
        return (
            f"{target} = pre.fineWall(l={wp.get('l')}, r={radius}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_vertex={wp.get('nb_vertex', 10)})"
        )
    if t == AvatarType.GRANULO_WALL:
        wp = av.wall_params or {}
        max_radius = wp.get("h", 2.0 * wp.get("rmax", 0.03)) / 2.0
        return (
            f"{target} = pre.granuloRoughWall(l={wp.get('l')}, "
            f"rmin={wp.get('rmin')}, rmax={max_radius}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}, "
            f"nb_vertex={wp.get('nb_vertex', 10)})"
        )
    if t == AvatarType.RIGID_CLUSTER:
        return (
            f"{target} = pre.rigidCluster(r={radius}, center={c}, "
            f"model={mod}, material={mat}, color={color!r}, nb_disk={av.nb_vertices})"
        )
    if t == AvatarType.RIGID_CYLINDER:
        wp = av.wall_params or {}
        hollow = ", is_Hollow=True" if av.is_hollow else ""
        return (
            f"{target} = pre.rigidCylinder(r={radius}, h={wp.get('h')}, "
            f"center={c}, model={mod}, material={mat}, color={color!r}{hollow})"
        )
    if t == AvatarType.RIGID_PLAN:
        ax = av.axis or {}
        return (
            f"{target} = pre.rigidPlan(center={c}, model={mod}, material={mat}, "
            f"color={color!r}, axe1={ax.get('axe1')}, axe2={ax.get('axe2')}, axe3={ax.get('axe3')})"
        )
    if t == AvatarType.RIGID_POLYGON:
        if av.generation_type == "regular":
            return (
                f"{target} = pre.rigidPolygon(model={mod}, material={mat}, center={c}, "
                f"color={color!r}, generation_type='regular', nb_vertices={av.nb_vertices}, "
                f"radius={radius})"
            )
        return (
            f"{target} = pre.rigidPolygon(model={mod}, material={mat}, center={c}, "
            f"color={color!r}, generation_type={av.generation_type!r}, "
            f"vertices=np.array({av.vertices}), radius={radius})"
        )
    if t == AvatarType.RIGID_POLYHEDRON:
        if av.generation_type == "regular":
            return (
                f"{target} = pre.rigidPolyhedron(model={mod}, material={mat}, "
                f"center={c}, color={color!r}, generation_type='regular', "
                f"nb_vertices={av.nb_vertices}, radius={radius})"
            )
        return (
            f"{target} = pre.rigidPolyhedron(model={mod}, material={mat}, "
            f"center={c}, color={color!r}, generation_type='vertices', "
            f"vertices=np.array({av.vertices}))"
        )
    if t == AvatarType.MESH_DEFORMABLE:
        mp = av.mesh_params or {}
        geom = mp.get("geom")
        if geom == "Rectangle":
            x0 = mp["cx"] - mp["lx"] / 2.0
            y0 = mp["cy"] - mp["ly"] / 2.0
            return (
                f"mesh_{ident} = pre.buildMesh2D({mp.get('mesh_type', '2T3')!r}, "
                f"{x0}, {y0}, {mp['lx']}, {mp['ly']}, {mp['nx']}, {mp['ny']})\n"
                f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        if geom == "Boîte (H8)":
            x0 = mp["cx"] - mp["lx"] / 2.0
            y0 = mp["cy"] - mp["ly"] / 2.0
            z0 = mp.get("cz", 0.0) - mp["lz"] / 2.0
            return (
                f"mesh_{ident} = pre.buildMeshH8({x0}, {y0}, {z0}, "
                f"{mp['lx']}, {mp['ly']}, {mp['lz']}, {mp['nx']}, {mp['ny']}, {mp['nz']})\n"
                f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        if geom == "Fichier externe":
            return (
                f"mesh_{ident} = pre.readMesh({mp.get('filepath', '')!r}, {mp.get('dim', 2)})\n"
                f"av_{ident} = pre.buildMeshedAvatar(mesh=mesh_{ident}, model={mod}, material={mat})"
            )
        return f"av_{ident} = None  # MESH_DEFORMABLE geom={geom!r} not emitted"
    if t == AvatarType.EMPTY_AVATAR:
        dimension = 3 if len(av.center) >= 3 else 2
        return "\n".join((
            f"{target} = pre.avatar({dimension})",
            f"{target}.addBulk(pre.rigid{dimension}d())",
            f"{target}.addNode(pre.node(coor=np.asarray({c}, dtype=float), number=1))",
            f"{target}.defineGroups()",
            f"{target}.defineModel(model={mod})",
            f"{target}.defineMaterial(material={mat})",
            f"{target}.computeRigidProperties()",
        ))
    return (
        f"# TODO {t.value}: av_{ident} — stored in .lmgc90, emit not yet specialised\n"
        f"av_{ident} = None"
    )


def _emit_contactors(av: Avatar) -> list[str]:
    ident = _ident(av.avatar_id)
    lines: list[str] = []
    for index, contactor in enumerate(av.contactors):
        shape = contactor.get("shape")
        if not shape:
            continue
        options = dict(contactor.get("params") or {})
        options.update({
            key: value for key, value in contactor.items()
            if key not in ("shape", "color", "params")
        })
        shape_key = str(shape).upper()
        generation_type = options.pop("generation_type", None)
        shift = options.pop("shift", None)

        if shape_key == "POLYG":
            if generation_type == "regular":
                count = int(options.pop("nb_vertices"))
                radius = float(options.pop("radius"))
                options["vertices"] = [
                    [
                        radius * math.cos(2.0 * math.pi * vertex / count),
                        radius * math.sin(2.0 * math.pi * vertex / count),
                    ]
                    for vertex in range(count)
                ]
                options["nb_vertices"] = count
            elif generation_type == "full":
                options["nb_vertices"] = len(options["vertices"])
            if shift is not None:
                options["vertices"] = [
                    [coordinate + shift[axis] for axis, coordinate in enumerate(vertex)]
                    for vertex in options["vertices"]
                ]

        elif shape_key == "POLYR":
            if generation_type == "regular":
                count = int(options.pop("nb_vertices"))
                radius = float(options.pop("radius"))
                vertices_name = f"_contactor_{ident}_{index}_vertices"
                faces_name = f"_contactor_{ident}_{index}_faces"
                lines.extend((
                    f"{faces_name}, {vertices_name} = pre.buildPolyhedronConnectivity("
                    f"pre.getRegularPolyhedronVertices({count}, {radius!r}))",
                ))
                options["vertices"] = vertices_name
                options["connectivity"] = faces_name
                options["nb_vertices"] = f"len({vertices_name})"
                options["nb_faces"] = f"len({faces_name})"
            elif generation_type == "full":
                options["nb_vertices"] = len(options["vertices"])
                options["nb_faces"] = len(options["connectivity"])
            if shift is not None:
                if isinstance(options["vertices"], str):
                    vertices_name = options["vertices"]
                    shifted_name = f"_contactor_{ident}_{index}_shifted_vertices"
                    lines.append(
                        f"{shifted_name} = {vertices_name} + np.array({shift!r})"
                    )
                    options["vertices"] = shifted_name
                else:
                    options["vertices"] = [
                        [coordinate + shift[axis] for axis, coordinate in enumerate(vertex)]
                        for vertex in options["vertices"]
                    ]

        kwargs = []
        for key, value in options.items():
            if key in ("nb_vertices", "nb_faces") and isinstance(value, str):
                value = value
            else:
                value = repr(value)
            kwargs.append(f"{key}={value}")
        extra = ", " + ", ".join(kwargs) if kwargs else ""
        color = contactor.get("color", av.color)
        lines.append(
            f"av_{ident}.addContactors(shape={shape!r}, color={color!r}{extra}, shift={shift!r})"
            f"\nav_{ident}.computeRigidProperties()"
        )
    return lines


def _emit_population(pop: ParticlePopulation) -> str:
    fn = {
        AvatarType.RIGID_DISK: "rigidDisk",
        AvatarType.RIGID_SPHERE: "rigidSphere",
        AvatarType.RIGID_DISCRETE: "rigidDiscreteDisk",
        AvatarType.RIGID_CLUSTER: "rigidCluster",
        AvatarType.RIGID_CYLINDER: "rigidCylinder",
    }.get(pop.avatar_type, "rigidDisk")
    extra = ""
    if pop.avatar_type == AvatarType.RIGID_CLUSTER:
        extra = f", nb_disk={pop.extra_params.get('nb_disk', 3)}"
    if pop.avatar_type == AvatarType.RIGID_CYLINDER:
        extra = f", h={pop.extra_params.get('h', 1.0)}"
    ident = pop.population_id[:12].replace("-", "_")
    return "\n".join([
        f"# population {pop.population_id}  n={len(pop)}  {pop.avatar_type.value}",
        f"centers_{ident} = np.array({pop.centers.tolist()})",
        f"radii_{ident}   = np.array({pop.radii.tolist()})",
        f"for _i, (_c, _r) in enumerate(zip(centers_{ident}, radii_{ident})):",
        f"    _body = pre.{fn}(r=float(_r), center=_c, model=mod_{pop.model_name}, "
        f"material=mat_{pop.material_name}, color={pop.color!r}{extra})",
        f"    bodies.addAvatar(_body)",
    ])


def _emit_law(law: ContactLaw) -> str:
    fric = f", fric={law.friction}" if law.friction is not None else ""
    extra = (", " + _kw(law.properties)) if law.properties else ""
    return (
        f"law_{law.name} = pre.tact_behav(name={law.name!r}, "
        f"law={law.law_type.value!r}{fric}{extra})"
    )


def _emit_see(rule: VisibilityRule, i: int) -> str:
    return (
        f"see_{i} = pre.see_table("
        f"CorpsCandidat={rule.candidate_body!r}, candidat={rule.candidate_contactor!r}, "
        f"colorCandidat={rule.candidate_color!r}, "
        f"CorpsAntagoniste={rule.antagonist_body!r}, antagoniste={rule.antagonist_contactor!r}, "
        f"colorAntagoniste={rule.antagonist_color!r}, "
        f"behav=law_{rule.behavior_name}, alert={rule.alert})"
    )


def _emit_dof(
    project: Project,
    op,
    avatar_refs: dict[str, str] | None = None,
) -> str:
    avatar_refs = avatar_refs or {}
    if op.target_type == "avatar":
        target = avatar_refs.get(
            str(op.target_value), f"av_{_ident(str(op.target_value))}"
        )
    elif op.target_type == "group":
        ids = project.avatar_groups.get(str(op.target_value), [])
        if not ids:
            return f"# DOF on empty group {op.target_value!r}"
        targets = [
            avatar_refs.get(aid, f"av_{_ident(aid)}")
            for aid in ids
        ]
    else:
        target = "bodies"
    params = ", ".join(f"{k}={v!r}" for k, v in op.parameters.items())
    if op.target_type == "group":
        return "\n".join(
            f"{target}.{op.operation_type}({params})"
            for target in targets
        )
    if op.operation_type == "imposeDrivenDof":
        return f"{target}.imposeDrivenDof({params})"
    if op.operation_type == "imposeInitValue":
        return f"{target}.imposeInitValue({params})"
    if op.operation_type == "translate":
        return f"{target}.translate({params})"
    if op.operation_type == "rotate":
        return f"{target}.rotate({params})"
    return f"{target}.{op.operation_type}({params})"
